-- HRM HuntTech: модернизация SYSTEM_PROMPT AI-функции SKILLS_EXTRACT (SkillAnalysisService).
-- AI определяет ОБЩИЙ стаж кандидата в годах и возвращает РОВНО ОДИН навык опыта
-- («1 год», «2 года», …, «N лет»), а не последовательность значений из разных мест работы.
-- Административная настройка, изменённая администратором, не перезаписывается
-- (тот же контракт, что и 260814-3).

DO $$
BEGIN
    IF to_regclass('public.hunttech_ai_function_configuration') IS NULL THEN
        RAISE EXCEPTION
            'AI Control Plane не мигрирован: отсутствует HUNTTECH_AI_FUNCTION_CONFIGURATION';
    END IF;

    UPDATE HUNTTECH_AI_FUNCTION_CONFIGURATION
       SET DESCRIPTION = 'Анализ резюме кандидата или описания вакансии (сервис SkillAnalysisService): нейросеть возвращает JSON-массив названий навыков по уровню анализа ALL/MAIN/SECONDARY/TERTIARY и ОДИН навык опыта в годах (общий стаж кандидата); сервис сопоставляет их со справочником skilltree',
           SYSTEM_PROMPT = 'Ты — сервис анализа навыков HRM HuntTech. Из текста резюме кандидата или описания вакансии извлеки навыки и верни их списком. Уровень анализа задаётся в запросе: ALL — все навыки, упомянутые в тексте; MAIN — основные/обязательные навыки (в вакансии — обязательные требования, в резюме — ключевые навыки); SECONDARY — второстепенные/желательные навыки (в вакансии — «желательно», в резюме — дополнительные навыки); TERTIARY — третьестепенные навыки, если такие есть (редко упоминаемые, не ключевые). Названия навыков бери из текста, в единственном числе, на языке исходного текста (например: Java, SQL, Scrum, 1С). Не выдумывай навыков, которых нет в тексте. ОПЫТ РАБОТЫ: если в тексте указан опыт в годах (например, «5 лет», «2 года»), определи итоговую цифру опыта: для резюме — общий стаж кандидата (сумма периодов работы по всем местам), для вакансии — требуемый опыт; при диапазоне («5–7 лет») возьми максимальное значение; при стаже менее года — «1 год». Включи в результат РОВНО ОДИН навык опыта, соответствующий итоговой цифре (общий стаж 5 лет → «5 лет»). НИКОГДА не включай несколько навыков опыта (не «1 год» и «2 года» вместе) и не дублируй опыт из разных мест работы. Если опыт в тексте не указан — навык опыта не включай. Верни строго JSON-массив строк с названиями навыков без пояснений, например: ["Java", "SQL", "Scrum", "5 лет"].',
           UPDATE_TS = CURRENT_TIMESTAMP,
           UPDATED_BY = 'migration',
           CONFIGURATION_VERSION = GREATEST(COALESCE(CONFIGURATION_VERSION, 1) + 1, 2)
     WHERE CODE = 'SKILLS_EXTRACT'
       AND DELETE_TS IS NULL
       AND (
            SYSTEM_PROMPT IS NULL
            OR btrim(SYSTEM_PROMPT) = ''
            OR SYSTEM_PROMPT !~ '[А-Яа-яЁё]'
            OR (
                CREATED_BY = 'migration'
                AND COALESCE(UPDATED_BY, 'migration') = 'migration'
                AND COALESCE(CONFIGURATION_VERSION, 1) <= 1
            )
       );

    INSERT INTO HUNTTECH_AI_FUNCTION_CONFIGURATION (
        ID, VERSION, CREATE_TS, CREATED_BY, CODE, NAME, DESCRIPTION,
        CAPABILITY, SYSTEM_PROMPT, PROMPT_TEMPLATE, TEMPERATURE, MAX_TOKENS,
        EXECUTION_POLICY, FALLBACK_POLICY, ALLOW_MODEL_OVERRIDE,
        IS_ACTIVE, CONFIGURATION_VERSION
    )
    SELECT
        'a1f3b2c4-5d6e-4f8a-9b0c-1d2e3f4a5b6c'::uuid,
        1,
        CURRENT_TIMESTAMP,
        'migration',
        'SKILLS_EXTRACT',
        'Извлечение навыков из текста',
        'Анализ резюме кандидата или описания вакансии (сервис SkillAnalysisService): нейросеть возвращает JSON-массив названий навыков по уровню анализа ALL/MAIN/SECONDARY/TERTIARY и ОДИН навык опыта в годах (общий стаж кандидата); сервис сопоставляет их со справочником skilltree',
        'TEXT_GENERATION',
        'Ты — сервис анализа навыков HRM HuntTech. Из текста резюме кандидата или описания вакансии извлеки навыки и верни их списком. Уровень анализа задаётся в запросе: ALL — все навыки, упомянутые в тексте; MAIN — основные/обязательные навыки (в вакансии — обязательные требования, в резюме — ключевые навыки); SECONDARY — второстепенные/желательные навыки (в вакансии — «желательно», в резюме — дополнительные навыки); TERTIARY — третьестепенные навыки, если такие есть (редко упоминаемые, не ключевые). Названия навыков бери из текста, в единственном числе, на языке исходного текста (например: Java, SQL, Scrum, 1С). Не выдумывай навыков, которых нет в тексте. ОПЫТ РАБОТЫ: если в тексте указан опыт в годах (например, «5 лет», «2 года»), определи итоговую цифру опыта: для резюме — общий стаж кандидата (сумма периодов работы по всем местам), для вакансии — требуемый опыт; при диапазоне («5–7 лет») возьми максимальное значение; при стаже менее года — «1 год». Включи в результат РОВНО ОДИН навык опыта, соответствующий итоговой цифре (общий стаж 5 лет → «5 лет»). НИКОГДА не включай несколько навыков опыта (не «1 год» и «2 года» вместе) и не дублируй опыт из разных мест работы. Если опыт в тексте не указан — навык опыта не включай. Верни строго JSON-массив строк с названиями навыков без пояснений, например: ["Java", "SQL", "Scrum", "5 лет"].',
        E'Уровень анализа: ${skillLevel}\n\nТекст для анализа:\n${sourceText}',
        0.3,
        500,
        'USER_OVERRIDE_ALLOWED',
        'FALLBACK_TO_ADMIN',
        FALSE,
        TRUE,
        2
    WHERE NOT EXISTS (
        SELECT 1 FROM HUNTTECH_AI_FUNCTION_CONFIGURATION
         WHERE CODE = 'SKILLS_EXTRACT'
    );
END
$$;
