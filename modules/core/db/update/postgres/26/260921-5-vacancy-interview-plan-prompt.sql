стек

развитие

Скрипт рекрутера:
[конкретный продающий блок]

4. Проверка кандидата по чек-листу (12–15 минут)
Цель блока:
Проверить соответствие кандидата обязательным требованиям

Структура блока:

Раздели вопросы по группам (на основе вакансии):

Ключевой опыт (домен / проекты)

Основной стек / технологии

Практический опыт (что делал руками)

Сложность задач / уровень самостоятельности

Формат:
Для каждого пункта:

Вопрос

